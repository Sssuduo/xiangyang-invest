def seed_chain_data(app):
    """幂等写入产业链招商基础数据（表非空则跳过）"""
    from models.chain import (ChainNode, ChainEnterprise, ChainGap, ChainTarget, ChainAdvice)
    from extensions import db

    try:
        if ChainNode.query.count() > 0:
            app.logger.info('[产业链招商] 基础数据已存在，跳过初始化')
            return

        for code, name, layer, order, desc in NODES:
            db.session.add(ChainNode(code=code, name=name, layer=layer, sort_order=order, description=desc))

        for (seq, name, industry, node_code, role, hightech, leader, scale,
             region, basis) in ENTERPRISES:
            db.session.add(ChainEnterprise(
                seq=seq, name=name, industry=industry, node_code=node_code, role=role,
                is_hightech=hightech, leader_level=leader, is_scale=scale,
                region=region, basis=basis, review_status='待复核'))

        for (gid, node_code, title, demand, supporters, evidence,
             f1, f2, f3, f4, f5, total, level, note) in GAPS:
            db.session.add(ChainGap(
                node_code=node_code, title=title, demand=demand,
                supporters=json.dumps(supporters, ensure_ascii=False),
                supporter_count=len(supporters),
                evidence=json.dumps(evidence, ensure_ascii=False),
                f1=f1, f2=f2, f3=f3, f4=f4, f5=f5,
                total_score=total, level=level, analysis_note=note, sort_order=gid))

        for (gap_id, name, node_code, region, products, scale, url, reason, is_local, scores) in TARGETS:
            total = int(round(
                scores.get('f1', 0) * 0.30 + scores.get('f2', 0) * 0.25 + scores.get('f3', 0) * 0.25
                + scores.get('f4', 0) * 0.10 + scores.get('f5', 0) * 0.10))
            db.session.add(ChainTarget(
                gap_id=gap_id, name=name, node_code=node_code, region=region, products=products,
                scale=scale, source_url=url, evidence=reason,
                scores=json.dumps(scores, ensure_ascii=False), total_score=total,
                is_local=is_local, review_status='待复核'))

        for (gap_id, title, content, kv) in ADVICE:
            db.session.add(ChainAdvice(
                gap_id=gap_id, title=title, content=content, kv=kv, sort_order=gap_id))

        db.session.commit()
        app.logger.info(
            f'[产业链招商] 基础数据初始化完成：环节 {len(NODES)} / 企业 {len(ENTERPRISES)} / '
            f'缺口 {len(GAPS)} / 目标企业 {len(TARGETS)} / 建议 {len(ADVICE)}')
    except Exception as exc:
        db.session.rollback()
        app.logger.warning(f'[产业链招商] 基础数据初始化失败: {exc}')
