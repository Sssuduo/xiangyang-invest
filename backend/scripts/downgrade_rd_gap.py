def load(name):
    p = os.path.join(BASE, name)
    with io.open(p, encoding='utf-8') as f:
        return json.load(f)


def save(name, data):
    p = os.path.join(BASE, name)
    with io.open(p, 'w', encoding='utf-8') as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2))


